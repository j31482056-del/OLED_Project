void OLED_SendCommand(uint8_t command)
{
	I2C_Start_condition();
	I2C_Send_SLA_W(OLED_I2C_ADDRESS);
	I2C_Write(0x00); // Control byte: Co = 0, D/C# = 0 (Command)
	I2C_Write(command);
	I2C_Stop();
}

void OLED_SendData(uint8_t data)
{
	I2C_Start_condition();
	I2C_Send_SLA_W(OLED_I2C_ADDRESS);
	I2C_Write(0x40); // Control byte: Co = 0, D/C# = 1 (Data)
	I2C_Write(data);
	I2C_Stop();
}

void OLED_Init(void)
{
	_delay_ms(100); // Display startup delay

	OLED_SendCommand(0xAE); // Display OFF
	OLED_SendCommand(0xD5); // Set Display Clock Divide Ratio
	OLED_SendCommand(0x80);
	OLED_SendCommand(0xA8); // Set Multiplex Ratio
	OLED_SendCommand(0x3F); // 1/64 duty
	OLED_SendCommand(0xD3); // Set Display Offset
	OLED_SendCommand(0x00);
	OLED_SendCommand(0x40); // Set Start Line
	OLED_SendCommand(0x8D); // Enable Charge Pump
	OLED_SendCommand(0x14);
	OLED_SendCommand(0x20); // Memory Addressing Mode
	OLED_SendCommand(0x02); // Page Addressing Mode
	OLED_SendCommand(0xA1); // Segment Remap
	OLED_SendCommand(0xC8); // COM Scan Direction
	OLED_SendCommand(0xDA); // Set COM Pins
	OLED_SendCommand(0x12);
	OLED_SendCommand(0x81); // Set Contrast
	OLED_SendCommand(0xCF);
	OLED_SendCommand(0xD9); // Set Pre-charge Period
	OLED_SendCommand(0xF1);
	OLED_SendCommand(0xDB); // Set VCOMH Deselect Level
	OLED_SendCommand(0x40);
	OLED_SendCommand(0xA4); // Entire Display ON (Resume RAM content)
	OLED_SendCommand(0xA6); // Normal Display
	OLED_SendCommand(0xAF); // Display ON

	OLED_Clear();
}

void OLED_SetCursor(uint8_t page, uint8_t column)
{
	if (page > 7) page = 7;
	if (column >= OLED_WIDTH) column = OLED_WIDTH - 1;

	OLED_SendCommand(0xB0 + page);                     // Set Page Start Address
	OLED_SendCommand(0x00 + (column & 0x0F));          // Set Lower Column Start Address
	OLED_SendCommand(0x10 + ((column >> 4) & 0x0F));   // Set Higher Column Start Address
}

void OLED_Clear(void)
{
	uint8_t page, col;
	for (page = 0; page < 8; page++)
	{
		OLED_SetCursor(page, 0);
		I2C_Start_condition();
		I2C_Send_SLA_W(OLED_I2C_ADDRESS);
		I2C_Write(0x40); // Stream Data
		for (col = 0; col < OLED_WIDTH; col++)
		{
			I2C_Write(0x00);
		}
		I2C_Stop();
	}
}

void OLED_DisplayChar(char c)
{
	if (c < 32 || c > 126)
	{
		c = ' ';
	}

	I2C_Start_condition();
	I2C_Send_SLA_W(OLED_I2C_ADDRESS);
	I2C_Write(0x40);

	for (uint8_t i = 0; i < 5; i++)
	{
		I2C_Write(OLED_Font5x7[c - 32][i]);
	}
	I2C_Write(0x00); // 1-pixel gap between characters
	I2C_Stop();
}

void OLED_DisplayString(const char *str)
{
	while (*str)
	{
		OLED_DisplayChar(*str++);
	}
}